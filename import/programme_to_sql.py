#!/usr/bin/env python3
"""Programme loader: JSON (packages + activities from a P6 export) → SQL that upserts `scheduler.programme_packages`
and `scheduler.programme_activities` on (project_id, code) / (package_id, code).

Re-running the SQL is safe: on a package that already exists it changes ONLY planned_start / planned_finish /
planned_days. Everything the team records on the package row — trade, subcontractor, value, owner, milestones,
authority approval, sort order, the name they may have tidied, cancelled — is left alone (db/020). New packages get
the P6 name and sort. Activities are programme-only, so they are upserted in full. One row goes into
`scheduler.programme_imports` per run.

Usage:
    python3 programme_to_sql.py sidra170_programme.json > sidra170_programme.sql

JSON shape (see sidra170_programme.json):
{
  "enquiry_no": "BBC/032026/00063",
  "source": "New_Schedule.pdf",          # the P6 export this came from
  "data_date": "2026-09-22",             # P6 data date
  "note": "Project RW-26-001: 208 days, 18-May-26 → 09-Feb-27",
  "project_start": "2026-05-18",          # optional: set projects.start_date / target_date if still blank
  "project_target": "2027-02-09",
  "packages": [ {"code": "RW-26-001.1", "name": "PRELIMINARIES", "days": 97, "start": "2026-05-18", "finish": "2026-09-23",
                 "activities": [ {"code": "A1000", "name": "Mobilization …", "days": 10, "start": "2026-05-18", "finish": "2026-06-03"}, … ]}, … ]
}
The SQL is written for the Supabase SQL editor and execute_sql alike: every table is schema-qualified and the data is
inline in one `do $$ … $$` block (the editor drops `search_path` between statements — handover 15 Oct).
"""
import json, sys
from datetime import date


def q(s):
    """SQL string literal."""
    return "NULL" if s is None else "'" + str(s).replace("'", "''") + "'"


def d(s):
    """Validate a date and return a literal."""
    if s is None:
        return "NULL"
    date.fromisoformat(s)
    return "'" + s + "'"


def main(path):
    with open(path, encoding="utf-8") as f:
        prog = json.load(f)
    enq = prog["enquiry_no"]
    pk = prog["packages"]
    acts = [(p["code"], a) for p in pk for a in p.get("activities", [])]
    out = []
    w = out.append
    w(f"-- {prog.get('note', '')}".rstrip())
    w(f"-- Programme for {enq} from {prog.get('source', '?')} (data date {prog.get('data_date', '?')}). Generated by import/programme_to_sql.py — edit the JSON, not this file.")
    w("-- Re-runnable: existing packages get new planned dates only; trade / subcontractor / value / owner / milestones / sort / name are left alone (db/020).")
    w("do $$")
    w("declare pid uuid; n_before int; n_pk int := 0; n_act int := 0;")
    w("begin")
    w(f"  select id into pid from scheduler.projects where enquiry_no = {q(enq)};")
    w(f"  if pid is null then raise exception 'Project {enq} not found'; end if;")
    w("  select count(*) into n_before from scheduler.programme_packages where project_id = pid;")
    w("")
    w("  -- packages: code, name, sort, days, start, finish")
    w("  insert into scheduler.programme_packages(project_id, code, name, sort, planned_days, planned_start, planned_finish) values")
    rows = []
    for i, p in enumerate(pk, 1):
        rows.append(f"    (pid, {q(p['code'])}, {q(p['name'])}, {i}, {p.get('days') if p.get('days') is not None else 'NULL'}, {d(p.get('start'))}, {d(p.get('finish'))})")
    w(",\n".join(rows))
    w("  on conflict (project_id, code) do update")
    w("    set planned_days = excluded.planned_days, planned_start = excluded.planned_start, planned_finish = excluded.planned_finish;")
    w("  get diagnostics n_pk = row_count;")
    w("")
    if acts:
        w("  -- activities: package code, activity id, name, days, start, finish")
        w("  with a(pcode, code, name, days, s, f) as (values")
        arows = []
        for pcode, a in acts:
            arows.append(f"    ({q(pcode)}, {q(a['code'])}, {q(a['name'])}, {a.get('days') if a.get('days') is not None else 'NULL'}, {d(a.get('start'))}, {d(a.get('finish'))})")
        w(",\n".join(arows))
        w("  )")
        w("  insert into scheduler.programme_activities(package_id, code, name, sort, planned_days, planned_start, planned_finish)")
        w("  select p.id, a.code, a.name, row_number() over (partition by a.pcode order by a.s::date, a.f::date), a.days, a.s::date, a.f::date")
        w("  from a join scheduler.programme_packages p on p.project_id = pid and p.code = a.pcode")
        w("  on conflict (package_id, code) do update")
        w("    set name = excluded.name, sort = excluded.sort, planned_days = excluded.planned_days,")
        w("        planned_start = excluded.planned_start, planned_finish = excluded.planned_finish;")
        w("  get diagnostics n_act = row_count;")
        w("")
    if prog.get("project_start") or prog.get("project_target"):
        w("  -- the project's own programme dates, only if not already set")
        w(f"  update scheduler.projects set start_date = coalesce(start_date, {d(prog.get('project_start'))}), target_date = coalesce(target_date, {d(prog.get('project_target'))}) where id = pid;")
        w("")
    w("  insert into scheduler.programme_imports(project_id, source, data_date, packages, activities, new_packages, note)")
    w(f"  values (pid, {q(prog.get('source', 'P6 export'))}, {d(prog.get('data_date'))}, n_pk, n_act, (select count(*) from scheduler.programme_packages where project_id = pid) - n_before, {q(prog.get('note'))});")
    w("end $$;")
    w("")
    w("select p.code, p.name, p.planned_start, p.planned_finish, p.status, p.supplier_id, p.value, count(a.id) as activities")
    w("from scheduler.programme_packages p left join scheduler.programme_activities a on a.package_id = p.id")
    w(f"join scheduler.projects j on j.id = p.project_id where j.enquiry_no = {q(enq)}")
    w("group by p.id order by p.sort;")
    sys.stdout.write("\n".join(out) + "\n")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
